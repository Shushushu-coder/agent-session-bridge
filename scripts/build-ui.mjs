// Bundles src/ui/app.ts into a single self-contained HTML resource and
// emits it as a TypeScript module so `tsc` carries it into dist/.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const marker = '/*__APP__*/';

const result = await build({
  entryPoints: [join(repoRoot, 'src/ui/app.ts')],
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  minify: true,
  write: false,
});

// Escape "</" so a literal "</script>" inside the bundle cannot close the
// host document's script tag early.
const js = result.outputFiles[0].text.replace(/<\//g, '<\\/');

const template = await readFile(join(repoRoot, 'src/ui/board.template.html'), 'utf8');
if (!template.includes(marker)) throw new Error(`template is missing the ${marker} marker`);
const html = template.replace(marker, () => js);

const out =
  '// Generated by scripts/build-ui.mjs — do not edit. Run npm run build:ui.\n' +
  `export const BOARD_HTML = ${JSON.stringify(html)};\n`;
const target = join(repoRoot, 'src/ui/boardHtml.generated.ts');
await writeFile(target, out, 'utf8');
console.log(`build-ui: ${target} (${html.length} bytes)`);
